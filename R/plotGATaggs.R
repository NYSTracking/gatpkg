#'plotGATaggs
#'
#'
#'@description This function makes a plot of one of the aggregation variables,
#'             with the title and data dependent on which aggregator variable 
#'             is selected.
#'             
#'             
#'
#'
#'
#'@param step Integer step in the GAT program, for help reference.
#'
#'@param closemap A boolean to denote whether to close the map windows after
#'                the maps are drawn and saved. The default setting is TRUE
#'                and will result in maps remaining open after GAT is
#'                finished running. Maps are saved to PDF irrespective of
#'                this setting.
#'
#'@param areaold A spatial polygons data frame.
#'
#'@param areanew A second spatial polygons data frame that should have the same
#'               outer boundary as the first one.
#'
#'@param aggvar The first variable by which polygons will be aggregated.
#'
#'@param gatvars A list of objects created by GAT. It contains thestrings myidvar,
#'               aggregator1, aggregator2, and boundary,which are all variables 
#'               in the area, the boolean popwt,and the numbers minvalue1 and 
#'               minvalue2.Both aggregator1 and aggregator2 must be numeric and
#'               myidvar must contain unique values.
#'               
#'@param exclist List of exclusion criteria to use when merging.
#'
#'@param myplots A list used to store the various plots generated by GAT.
#'
#'@param mapvars A set of variables and descriptors used for some of the mapping functions.
#'
#'
#'
#'@export




# plot aggregation variable
plotGATaggs <- function(step, closemap, areaold, areanew, aggvar, gatvars, exclist, myplots,  mapvars){
  
  
  temp <- defineGATmapclasses(areaold = areaold,
                              areanew = areanew,
                              aggvar = aggvar)
  
  mapvars <- createGATmapvar(temp = temp, gatvars = gatvars, exclist = exclist, areaold = areaold, areanew = areanew,
                             aggvar = aggvar, myplots = myplots, mapvars = mapvars, step = step)
  
  
  plotbefore <- plotGATmaps(areaold,
                            aggvar,
                            title.main = mapvars$title,
                            title.sub = mapvars$titlesub,
                            colcode = mapvars$colcodebefore,
                            mapstats = TRUE,
                            closemap = closemap)
  
  
  
  # find the new maximums after aggregation
  mapvars$titlemain <- paste(aggvar, "After Merging")
  plotafter <- plotGATmaps(areanew,
                           aggvar,
                           title.main = mapvars$titlemain,
                           title.sub = mapvars$titlesub,
                           colcode = mapvars$colcodeafter,
                           after = TRUE, mapstats = TRUE,
                           closemap = closemap)
  
  if(aggvar == gatvars$aggregator1){
    myplots$aggregator1before = plotbefore
    myplots$aggregator1after = plotafter
  } else{
    myplots$aggregator2before = plotbefore
    myplots$aggregator2after = plotafter
  }
  return(myplots)
}
