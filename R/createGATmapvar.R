#'createGATmapvar
#'
#'@description This function creates the map variables to be included in the aggregator plot(s).
#'
#'@param temp A temporary variable, in this case storing the color code.
#'
#'@param gatvars A list of objects created by GAT. It contains thestrings myidvar,
#'               aggregator1, aggregator2, and boundary,which are all variables 
#'               in the area, the boolean popwt,and the numbers minvalue1 and 
#'               minvalue2.Both aggregator1 and aggregator2 must be numeric and
#'               myidvar must contain unique values.
#'                
#'@param exclist List of exclusion criteria to use when merging.
#'
#'@param areaold A spatial polygons data frame.
#'
#'@param areanew A second spatial polygons data frame that should have the same outer
#'               boundary as the first one.
#'
#'@param aggvar The first variable by which polygons will be aggregated.
#'
#'@param myplots A list used to store the various plots generated by GAT.
#'
#'@param mapvars A set of variables and descriptors used for some of the mapping functions.
#'
#'@param step Integer step in the GAT program, for help reference.
#'
#'
#'
#'
#'
#'@export



createGATmapvar = function(temp, gatvars, exclist, areaold, areanew, aggvar, myplots, mapvars, step){
  
  numformat <- function(num) {
    format(as.numeric(gsub(",", "", num)), big.mark=",", scientific=FALSE)
  }
  
  if(aggvar == gatvars$aggregator1){
    aggmin = gatvars$minvalue1
    aggmax = gatvars$maxvalue1
  } else{
    aggmin = gatvars$minvalue2
    aggmax = gatvars$maxvalue2
  }
  
  mapvars$title <- paste(aggvar, "Before Merging")
  mapvars$titlesub = paste("Aggregation values:",
                           numformat(aggmin), "to",
                           numformat(as.numeric(gsub(",", "",
                                                     aggmax))),
                           aggvar)
  
  
  
  #can most likely be made into a separate function
  for(i in seq(1, 9, by = 3)){
    if(exclist[i] != "NONE"){
      textseparation <- if(i == 1) "\nExclusion criteria: " else ";"
      
      mapvars$titlesub <- paste(mapvars$titlesub, textseparation,
                                exclist[i], exclist[i + 1],
                                numformat(exclist[i + 2]))
    }
    
  }
  mapvars$colcodebefore <- temp$colcodebefore
  mapvars$colcodeafter <- temp$colcodeafter
  return(mapvars)
}
